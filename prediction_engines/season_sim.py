class PbpWriter:
    """Every simulated game's rows, appended to one compressed file."""

    def __init__(self, path):
        self._handle = gzip.open(path, "wt", encoding="utf-8", newline="")
        self._wrote_header = False

    def write(self, frame):
        frame.to_csv(self._handle, index=False, header=not self._wrote_header)
        self._wrote_header = True

    def close(self):
        self._handle.close()


def _lines_from_real_box(game_box, profiles, league):
    """Team -> (profiles, minutes) for one real game: who played, and how long."""
    sheets = {}
    for team, rows in game_box.groupby("team"):
        players = [profiles.get(int(pid)) or replacement_profile(pid, name, league)
                   for pid, name in zip(rows["person_id"], rows["name"])]
        sheets[team] = (players, list(rows["minutes"]))
    return sheets


@dataclass
class SeasonSetup:
    """Everything a season is simulated from; built once, simulated many times."""
    mode: str
    season: str
    league: League
    profiles: dict
    priors: dict               # tricode -> TeamPrior
    schedule: pd.DataFrame
    team_rosters: dict         # tricode -> [PlayerProfile]; empty in mechanics mode
    real_by_game: dict         # game_id -> that game's real box rows; mechanics mode only
    history_games: pd.DataFrame
    history_box: pd.DataFrame


def prepare_season(mode, season, sandbox):
    """Read the history and build what `mode` simulates the season from."""
    games = load_games()
    box = load_box(games)
    if mode == "mechanics":
        league = build_league(box, season)
        profiles = build_profiles(box, {season: 1.0}, season, league)
        priors = build_team_priors(box, season, shrink=1.0)
        real_by_game = dict(tuple(box[box["season"] == season].groupby("game_id")))
        return SeasonSetup(mode, season, league, profiles, priors,
                           schedule_from_history(games, season), {}, real_by_game, games, box)

    history = previous_seasons(games, season, 2)
    latest = history[-1]
    league = build_league(box, latest)
    weights = {latest: 1.0, **({history[0]: 0.5} if len(history) > 1 else {})}
    profiles = build_profiles(box, weights, latest, league)
    raw_priors = build_team_priors(box, latest, shrink=1.0)
    if mode == "forecast":
        schedule = fetch_schedule(season, sandbox)
        rosters = fetch_rosters(season, {t: p.team_id for t, p in raw_priors.items()}, sandbox)
    else:
        schedule = schedule_from_history(games, season)
        rosters = opening_rosters(box, season)
    team_rosters = {
        team: [profiles.get(int(pid)) or replacement_profile(pid, name, league)
               for pid, name in zip(rows["person_id"], rows["name"])]
        for team, rows in rosters.groupby("team")}
    unknown = sorted(set(schedule["home"]) - set(team_rosters))
    if unknown:
        raise RuntimeError(f"fiksturde kadrosu olmayan takim var: {unknown}")
    priors = carried_priors(raw_priors, team_rosters, box, latest, league, TEAM_EFFECT_KEPT)
    return SeasonSetup(mode, season, league, profiles, priors, schedule, team_rosters, {},
                       games, box)


def simulate_season(setup, sandbox, seed, keep_events=True, team_shock_sd=0.0, verbose=True):
    """Play the schedule through once.

    Returns (games, lines, values, extras). With keep_events the play-by-play
    is written to the sandbox and the impact engine is run on every game;
    without it only results and box lines are produced, which costs seconds.
    `team_shock_sd` draws each team's shooting for the season - a replication's
    way of not knowing how good the teams really are.
    """
    rng = random.Random(seed)
    priors = setup.priors
    if team_shock_sd > 0:
        priors = {team: TeamPrior(p.tricode, p.team_id, p.pace, p.defence, p.forced_turnovers,
                                  form=math.exp(rng.gauss(0, team_shock_sd)))
                  for team, p in sorted(priors.items())}
    simulator = GameSimulator(setup.league, rng, keep_events=keep_events)
    availability = Availability(rng)
    writer = PbpWriter(sandbox.path("pbp.csv.gz")) if keep_events else None
    game_rows, line_rows, value_rows = [], [], []
    extras = {"impact_cache": {}, "value_cache": {}, "assist_mismatches": 0}
    t0 = time.time()
    schedule = setup.schedule[["game_id", "game_date", "home", "away"]]
    try:
        for n, (game_id, date, home, away) in enumerate(schedule.itertuples(index=False), 1):
            if setup.mode == "mechanics":
                real = _lines_from_real_box(setup.real_by_game[game_id], setup.profiles,
                                            setup.league)
                if home not in real or away not in real:
                    continue
                sheets = tuple(TeamSheet(priors[t], *real[t]) for t in (home, away))
            else:
                sheets = tuple(dressed_sheet(priors[t], setup.team_rosters[t], availability)
                               for t in (home, away))
            game = simulator.play(game_id, *sheets)
            game_rows.append({"game_id": game_id, "game_date": date, "home": home, "away": away,
                              "home_points": game.home_points, "away_points": game.away_points,
                              "periods": game.periods})
            for line in game.lines:
                line_rows.append({"game_date": date, **line})
            if keep_events:
                frame, weighted, unweighted, assists_agree = score_game(game, sheets)
                writer.write(frame)
                extras["value_cache"][game_id] = weighted
                extras["impact_cache"][game_id] = _impact_entry(unweighted, home, away)
                extras["assist_mismatches"] += 0 if assists_agree else 1
                for line in game.lines:
                    pid = line["person_id"]
                    w, u = weighted.get(pid), unweighted.get(pid)
                    value_rows.append({"game_id": game_id, "person_id": pid,
                                       "value": w["value"] if w else 0.0,
                                       "value_unweighted": u["value"] if u else 0.0,
                                       **{c: (w[c] if w else 0.0)
                                          for c in value_engine.COMPONENTS}})
            if verbose and n % 200 == 0:
                print(f"    {n}/{len(schedule)} mac ({time.time() - t0:.0f} sn)", flush=True)
    finally:
        if writer is not None:
            writer.close()
    return pd.DataFrame(game_rows), pd.DataFrame(line_rows), pd.DataFrame(value_rows), extras


def _impact_entry(unweighted, home, away):
    """One game's entry in the impact cache layout the rest of the project reads."""
    sums = {home: 0.0, away: 0.0}
    players = {}
    for pid, e in unweighted.items():
        if e["team"] in sums:
            sums[e["team"]] += e["value"]
        if not (isinstance(pid, str) and pid.startswith("name:")):
            players[int(pid)] = {"impact": e["value"], "team": e["team"], "name": e["name"],
                                 "person_id": int(pid)}
    return {"home_impact": sums[home], "away_impact": sums[away], "players": players}


# ---------------------------------------------------------------------------
#  Reading a season back
# ---------------------------------------------------------------------------
def standings(games):
    rows = defaultdict(lambda: {"wins": 0, "losses": 0, "points_for": 0, "points_against": 0})
    for home, away, hp, ap in games[["home", "away", "home_points", "away_points"]].itertuples(index=False):
        for team, mine, theirs in ((home, hp, ap), (away, ap, hp)):
            r = rows[team]
            r["wins" if mine > theirs else "losses"] += 1
            r["points_for"] += mine
            r["points_against"] += theirs
    table = pd.DataFrame.from_dict(rows, orient="index").rename_axis("team").reset_index()
    played = table["wins"] + table["losses"]
    table["margin"] = (table["points_for"] - table["points_against"]) / played
    table["win_pct"] = table["wins"] / played
    return table.sort_values(["win_pct", "margin"], ascending=False).reset_index(drop=True)


def league_averages(lines, games):
    """Per team-game averages and the shape of the results."""
    team = lines.groupby(["game_id", "team"])[list(LINE_STATS)].sum()
    means = team.mean()
    margin = games["home_points"] - games["away_points"]
    total = games["home_points"] + games["away_points"]
    poss = team["fga"] - team["oreb"] + team["tov"] + 0.44 * team["fta"]
    return {"pts": means["pts"], "fga": means["fga"], "fg3a": means["fg3a"], "fta": means["fta"],
            "oreb": means["oreb"], "dreb": means["dreb"], "ast": means["ast"], "stl": means["stl"],
            "blk": means["blk"], "tov": means["tov"], "pf": means["pf"],
            "fg_pct": team["fgm"].sum() / team["fga"].sum(),
            "fg3_pct": team["fg3m"].sum() / team["fg3a"].sum(),
            "ft_pct": team["ftm"].sum() / team["fta"].sum(),
            "possessions": poss.mean(), "home_win_pct": (margin > 0).mean(),
            "home_margin": margin.mean(), "margin_sd": margin.std(), "total_sd": total.std(),
            "overtime_share": (games["periods"] > 4).mean() if "periods" in games else float("nan")}


def real_reference(games, box, season):
    """The same averages for the season as it was actually played."""
    g = games[games["season"] == season]
    real_games = pd.DataFrame({"game_id": g["game_id"], "home": g["home_abbr"], "away": g["away_abbr"],
                               "home_points": g["home_pts"], "away_points": g["away_pts"]})
    return league_averages(box[box["season"] == season], real_games), standings(real_games)


def compare_with_real(sim_lines, sim_games, games, box, season):
    real_avg, real_table = real_reference(games, box, season)
    sim_avg, sim_table = league_averages(sim_lines, sim_games), standings(sim_games)
    columns = ["team", "wins", "losses", "margin", "points_for", "points_against"]
    both = real_table[columns].merge(sim_table[columns], on="team", suffixes=("_real", "_sim"))
    for kind in ("real", "sim"):
        played = both[f"wins_{kind}"] + both[f"losses_{kind}"]
        for side in ("points_for", "points_against"):
            both[f"{side}_{kind}"] = both[f"{side}_{kind}"] / played

    def corr(column):
        return float(both[f"{column}_real"].corr(both[f"{column}_sim"]))

    return {"averages": {k: (float(real_avg[k]), float(sim_avg[k])) for k in sim_avg},
            "teams": both, "wins_correlation": corr("wins"),
            "wins_mean_abs_error": float((both["wins_real"] - both["wins_sim"]).abs().mean()),
            "margin_correlation": corr("margin"), "offence_correlation": corr("points_for"),
            "defence_correlation": corr("points_against"),
            "margin_spread": (float(both["margin_real"].std()), float(both["margin_sim"].std()))}


def player_table(lines, values):
    """Per-game averages for everyone who dressed, with the engine's value."""
    merged = lines.merge(values, on=["game_id", "person_id"], how="left") if len(values) else lines
    stats = ["minutes", "pts", "oreb", "dreb", "ast", "stl", "blk", "tov"]
    extra = ["value"] if "value" in merged.columns else []
    table = merged.groupby(["person_id", "name"]).agg(
        team=("team", "last"), games=("game_id", "size"),
        **{s: (s, "mean") for s in stats + extra},
        fgm=("fgm", "sum"), fga=("fga", "sum"), fg3m=("fg3m", "sum"), fg3a=("fg3a", "sum"),
        ftm=("ftm", "sum"), fta=("fta", "sum")).reset_index()
    table["reb"] = table["oreb"] + table["dreb"]
    table["ts"] = (table["pts"] * table["games"]) / (2 * (table["fga"] + 0.44 * table["fta"])).replace(0, np.nan)
    return table


def build_ranking_engine(sim_games, lines, values, history_games, season):
    """The project's own ranking engine over the simulated season.

    Real seasons before it are included so that Elo carries into the
    simulated one; nothing real is modified - the engine is built in memory.
    """
    rankings = _load_sibling("power_rankings")
    earlier = history_games[history_games["season"] < season]
    real = pd.DataFrame({"game_id": earlier["game_id"], "game_date": earlier["game_date"],
                         "season": earlier["season"], "home_team": earlier["home_abbr"],
                         "away_team": earlier["away_abbr"], "home_score": earlier["home_pts"],
                         "away_score": earlier["away_pts"], "point_diff": earlier["margin"]})
    sim = pd.DataFrame({"game_id": sim_games["game_id"],
                        "game_date": pd.to_datetime(sim_games["game_date"]), "season": season,
                        "home_team": sim_games["home"], "away_team": sim_games["away"],
                        "home_score": sim_games["home_points"], "away_score": sim_games["away_points"],
                        "point_diff": sim_games["home_points"] - sim_games["away_points"]})
    merged = lines.merge(values[["game_id", "person_id", "value", "value_unweighted"]],
                         on=["game_id", "person_id"], how="left")
    player_games = pd.DataFrame({
        "player": merged["person_id"], "name": merged["name"], "team": merged["team"],
        "game_id": merged["game_id"], "game_date": pd.to_datetime(merged["game_date"]),
        "season": season, "impact": merged["value_unweighted"].fillna(0.0),
        "minutes": merged["minutes"], "value": merged["value"].fillna(0.0)})
    return rankings.RankingEngine(pd.concat([real, sim], ignore_index=True), player_games)


def power_ranking(sim_games, lines, values, history_games, season):
    engine = build_ranking_engine(sim_games, lines, values, history_games, season)
    return engine.rank("season", season), engine.players("season", season, None, 25)


