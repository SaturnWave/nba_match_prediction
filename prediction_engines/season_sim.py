"""
Season simulator: play a whole season in a sandbox, possession by possession.

WHAT IT IS
    A generative model of NBA games at the level the play-by-play records
    them. Every possession is drawn - who ends it, a shot or a turnover or a
    trip to the line, whether the shot falls, who passed, who rebounded - and
    written as rows in the real feed's own layout and wording, so the
    project's impact engine (value_engine.py) reads a simulated game exactly
    as it reads a real one. A season is the schedule played through in date
    order, with players drifting in and out of availability, and the impact
    score computed on every simulated game as it is played.

WHAT DRIVES A GAME
    Player profiles measured from the box scores of the seasons before: per-
    minute rates of shots, free-throw trips, turnovers, assists, rebounds,
    steals, blocks and fouls, and shooting percentages, each pulled toward a
    replacement level by how little the player has played. A team is the
    minutes-weighted sum of who is dressed. Three things come from the team
    rather than its players, because the box score has no individual measure
    of them: pace, how well opponents shoot against it, and how often it
    forces turnovers. In a forecast those follow the players: each carries the
    effects of the team he played for last season, and a team's is the average
    of what its roster brings.

    The league-wide proportions (how many made twos are assisted, how many
    missed twos are blocks, how many turnovers are steals, what kinds of
    free-throw trip there are) were measured on 200 real games of 2025-26 and
    are the constants below.

    The trained prediction models are NOT used to generate games. That is
    deliberate: a world generated by the model could only ever agree with it,
    and this one can be used to test it.

THREE MODES
    forecast    a season not yet played: the published schedule and the
                current rosters (nba_api), profiles from the last two seasons
    backtest    a season already played, simulated as if it were not: profiles
                and team priors from the seasons before it, opening-night
                rosters. Says how far a forecast can be trusted
    mechanics   a season already played, with each game's real lineup and
                minutes and that season's own profiles. Says whether the
                generator itself is right: league totals and team records
                should come out close to the real ones

ISOLATION
    Reads the local caches; writes only under sim_sandbox/<run>/. Sandbox.path
    refuses any target outside that directory, and every run fingerprints the
    project's data before and after and reports whether anything moved.

Run:  py prediction_engines/season_sim.py forecast --season 2026_2027
      py prediction_engines/season_sim.py mechanics --season 2025_2026
      py prediction_engines/season_sim.py backtest --season 2025_2026
      py prediction_engines/season_sim.py show --run forecast_2026_2027 --game 0022600001
"""
