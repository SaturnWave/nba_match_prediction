class Sandbox:
    """The one directory a run may write to."""

    def __init__(self, name):
        self.name = name
        self.root = os.path.abspath(os.path.join(SANDBOX_ROOT, name))
        os.makedirs(self.root, exist_ok=True)

    def path(self, *parts):
        target = os.path.abspath(os.path.join(self.root, *parts))
        if os.path.commonpath([target, self.root]) != self.root:
            raise ValueError(f"sandbox disina yazma reddedildi: {target}")
        os.makedirs(os.path.dirname(target), exist_ok=True)
        return target


def fingerprint_project():
    """What the project's data looks like right now, for a before/after check.

    Tracked files through `git status` (any change to a tracked file or any
    new untracked one shows there); the ignored caches by size and mtime.
    The sandbox is ignored by git and is not part of the fingerprint.
    """
    status = subprocess.run(["git", "status", "--porcelain"], cwd=PROJECT_ROOT,
                            capture_output=True, text=True, timeout=120, check=True).stdout
    entries = []
    for relative in PROTECTED_UNTRACKED:
        target = os.path.join(PROJECT_ROOT, relative)
        files = ([target] if os.path.isfile(target) else
                 [os.path.join(target, f) for f in sorted(os.listdir(target))]
                 if os.path.isdir(target) else [])
        for f in files:
            stat = os.stat(f)
            entries.append(f"{os.path.relpath(f, PROJECT_ROOT)}:{stat.st_size}:{stat.st_mtime_ns}")
    return hashlib.sha1((status + "\n".join(entries)).encode("utf-8")).hexdigest()


