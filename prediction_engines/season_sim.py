def engine_context(game, sheets):
    """What the value engine takes from the box score, built from the simulated one."""
    final, passers = {}, defaultdict(list)
    first_names = {p.person_id: p for sheet in sheets for p in sheet.players}
    for line in game.lines:
        if line["ast"] > 0:
            p = first_names[line["person_id"]]
            final[p.person_id] = line["ast"]
            passers[line["team"]].append((p.person_id, p.first, p.surname))
    return value_engine.GameContext(final, dict(passers), {})


ENGINE_FIELDS = ("name", "team", "value", "events") + tuple(value_engine.COMPONENTS)


def score_game(game, sheets):
    """Run the impact engine on a simulated game.

    Returns (frame, weighted, unweighted, assists_agree). The last is the
    end-to-end check on generator and engine together: the engine, reading
    nothing but the rows, must credit every player exactly the assists the
    generator handed him.
    """
    frame = game.frame()
    context = engine_context(game, sheets)
    raw = value_engine.compute_game_value(frame, True, context, raw=True)
    handed_out = {line["person_id"]: line["ast"] for line in game.lines}
    assists_agree = all(int(raw[pid]["assists_n"]) == n if pid in raw else n == 0
                        for pid, n in handed_out.items())
    weighted = {pid: {k: e[k] for k in ENGINE_FIELDS} for pid, e in raw.items()}
    unweighted = value_engine.compute_game_value(frame, False, context)
    return frame, weighted, unweighted, assists_agree


