@dataclass(frozen=True)
class PlayerProfile:
    person_id: int
    name: str
    first: str
    surname: str
    minutes_per_game: float
    availability: float
    rates: dict                # per minute, by RATE_KINDS
    fg2: float
    fg3: float
    ft: float
    has_history: bool


@dataclass(frozen=True)
class League:
    """League-wide levels the profiles are shrunk toward and scaled against."""
    rates: dict                # per player-minute
    replacement_rates: dict
    fg2: float
    fg3: float
    ft: float
    replacement_fg2: float
    replacement_fg3: float
    replacement_ft: float
    pace: float


@dataclass(frozen=True)
class TeamPrior:
    tricode: str
    team_id: int
    pace: float                # possessions per 48 minutes
    defence: float             # opponents' effective shooting against it, league = 1
    forced_turnovers: float    # opponents' turnover rate against it, league = 1
    form: float = 1.0          # its own shooting this season; 1 unless a replication draws it


def split_name(full_name):
    first, _, surname = str(full_name).partition(" ")
    return first, surname or first


def _with_derived(frame):
    out = frame.copy()
    out["fga2"] = out["fga"] - out["fg3a"]
    out["fga3"] = out["fg3a"]
    out["fg2m"] = out["fgm"] - out["fg3m"]
    out["trips"] = out["fta"] * TRIPS_PER_FTA
    return out


def build_league(box, season):
    """League and replacement levels from one season's box scores."""
    b = _with_derived(box[box["season"] == season])
    per_player = b.groupby("person_id").agg(minutes=("minutes", "sum"), games=("minutes", "size"))
    bench_ids = per_player.index[per_player["minutes"] / per_player["games"] < BENCH_MINUTES_PER_GAME]
    bench = b[b["person_id"].isin(bench_ids)]

    def rates(frame):
        return {k: float(frame[k].sum() / frame["minutes"].sum()) for k in RATE_KINDS}

    def shooting(frame):
        return (float(frame["fg2m"].sum() / frame["fga2"].sum()),
                float(frame["fg3m"].sum() / frame["fg3a"].sum()),
                float(frame["ftm"].sum() / frame["fta"].sum()))

    fg2, fg3, ft = shooting(b)
    r_fg2, r_fg3, r_ft = shooting(bench)
    return League(rates(b), rates(bench), fg2, fg3, ft, r_fg2, r_fg3, r_ft,
                  pace=float(team_game_table(b)["pace"].mean()))


def build_profiles(box, season_weights, latest, league):
    """{person_id: PlayerProfile} from weighted seasons of box scores.

    `latest` is the season minutes and availability are read from: how much a
    player plays is taken from his most recent season, how he plays from all
    the weighted ones.
    """
    b = _with_derived(box[box["season"].isin(season_weights)])
    b = b.assign(weight=b["season"].map(season_weights).astype(float))
    stats = list(RATE_KINDS) + ["fg2m", "fg3m", "fg3a", "ftm", "fta", "minutes"]
    weighted = b[stats].multiply(b["weight"], axis=0)
    weighted["person_id"] = b["person_id"].values
    totals = weighted.groupby("person_id").sum()
    names = b.sort_values("game_date").groupby("person_id")["name"].last()

    recent = b[b["season"] == latest]
    season_games = recent.groupby("team")["game_id"].nunique().max() if len(recent) else 82
    recent_use = recent.groupby("person_id").agg(games=("minutes", "size"), minutes=("minutes", "sum"))

    profiles = {}
    for pid, t in totals.iterrows():
        minutes = float(t["minutes"])
        rates = {k: (t[k] + PRIOR_MINUTES * league.replacement_rates[k]) / (minutes + PRIOR_MINUTES)
                 for k in RATE_KINDS}
        fg2 = (t["fg2m"] + PRIOR_ATTEMPTS["fg2"] * league.fg2) / (t["fga2"] + PRIOR_ATTEMPTS["fg2"])
        fg3 = (t["fg3m"] + PRIOR_ATTEMPTS["fg3"] * league.fg3) / (t["fg3a"] + PRIOR_ATTEMPTS["fg3"])
        ft = (t["ftm"] + PRIOR_ATTEMPTS["ft"] * league.ft) / (t["fta"] + PRIOR_ATTEMPTS["ft"])
        if pid in recent_use.index and recent_use.at[pid, "games"] >= 10:
            use = recent_use.loc[pid]
            per_game = float(use["minutes"] / use["games"])
            availability = float(np.clip(use["games"] / season_games, *AVAILABILITY_RANGE))
        else:
            # Little or nothing last season: he plays less, and less reliably.
            games_any = max(1, int((b["person_id"] == pid).sum()))
            per_game = 0.8 * float(b.loc[b["person_id"] == pid, "minutes"].sum() / games_any)
            availability = 0.75
        first, surname = split_name(names[pid])
        profiles[int(pid)] = PlayerProfile(int(pid), str(names[pid]), first, surname, per_game,
                                           availability, rates, float(fg2), float(fg3), float(ft),
                                           has_history=True)
    return profiles


def replacement_profile(person_id, name, league):
    """A player with no NBA history: replacement rates, a few minutes a night."""
    first, surname = split_name(name)
    return PlayerProfile(int(person_id), str(name), first, surname, UNKNOWN_MINUTES_PER_GAME,
                         UNKNOWN_AVAILABILITY, dict(league.replacement_rates),
                         league.replacement_fg2, league.replacement_fg3, league.replacement_ft,
                         has_history=False)


def team_game_table(box):
    """One row per team-game: possessions, pace and what the opponent did."""
    b = _with_derived(box) if "fga2" not in box.columns else box
    team = (b.groupby(["game_id", "team", "team_id"])
            .agg(minutes=("minutes", "sum"), fga=("fga", "sum"), fgm=("fgm", "sum"),
                 fg3m=("fg3m", "sum"), fta=("fta", "sum"), oreb=("oreb", "sum"),
                 tov=("tov", "sum")).reset_index())
    team["poss"] = team["fga"] - team["oreb"] + team["tov"] + 0.44 * team["fta"]
    other = team[["game_id", "team", "fga", "fgm", "fg3m", "tov", "poss"]].rename(
        columns={c: f"opp_{c}" for c in ("team", "fga", "fgm", "fg3m", "tov", "poss")})
    both = team.merge(other, on="game_id")
    both = both[both["team"] != both["opp_team"]].copy()
    both["pace"] = (both["poss"] + both["opp_poss"]) / 2.0 * TEAM_MINUTES / both["minutes"]
    return both


def build_team_priors(box, season, shrink):
    """{tricode: TeamPrior} from one season, pulled toward the league by 1 - shrink."""
    table = team_game_table(box[box["season"] == season])
    league_efg = (table["opp_fgm"].sum() + 0.5 * table["opp_fg3m"].sum()) / table["opp_fga"].sum()
    league_tov = table["opp_tov"].sum() / table["opp_poss"].sum()
    league_pace = table["pace"].mean()
    priors = {}
    for (tricode, team_id), t in table.groupby(["team", "team_id"]):
        efg = (t["opp_fgm"].sum() + 0.5 * t["opp_fg3m"].sum()) / t["opp_fga"].sum()
        tov = t["opp_tov"].sum() / t["opp_poss"].sum()
        priors[tricode] = TeamPrior(
            tricode, int(team_id),
            pace=float(league_pace + shrink * (t["pace"].mean() - league_pace)),
            defence=float(1.0 + shrink * (efg / league_efg - 1.0)),
            forced_turnovers=float(1.0 + shrink * (tov / league_tov - 1.0)))
    return priors


def carried_priors(raw_priors, rosters, box, season, league, kept):
    """Next season's team effects, carried there by the players.

    Defence, forced turnovers and pace are measured per team because the box
    score has no individual measure of them - but they belong to the players
    who produced them, and players move. Each player carries the effects of
    the team(s) he played for last season, in proportion to his minutes there;
    a team's effect next season is the average of what its roster brings,
    weighted by how much each is expected to play. A team that kept everyone
    keeps its defence; a team that traded for half of a great defence gets
    half of it. `kept` pulls the result toward the league, because even an
    unchanged roster does not repeat itself exactly.
    """
    played = (box[box["season"] == season].groupby(["person_id", "team"])["minutes"].sum()
              .reset_index())
    carried = defaultdict(lambda: [0.0, 0.0, 0.0, 0.0])    # minutes, defence, forced, pace
    for pid, team, minutes in played.itertuples(index=False):
        prior = raw_priors.get(team)
        if prior is None:
            continue
        c = carried[int(pid)]
        c[0] += minutes
        c[1] += minutes * prior.defence
        c[2] += minutes * prior.forced_turnovers
        c[3] += minutes * prior.pace

    out = {}
    for team, roster in rosters.items():
        weight = defence = forced = pace = 0.0
        for profile in roster:
            c = carried.get(profile.person_id)
            if c is None or c[0] <= 0:
                continue
            w = profile.minutes_per_game * profile.availability
            weight += w
            defence += w * c[1] / c[0]
            forced += w * c[2] / c[0]
            pace += w * c[3] / c[0]
        base = raw_priors[team]
        if weight <= 0:
            out[team] = TeamPrior(team, base.team_id, league.pace, 1.0, 1.0)
            continue
        out[team] = TeamPrior(team, base.team_id,
                              pace=league.pace + kept * (pace / weight - league.pace),
                              defence=1.0 + kept * (defence / weight - 1.0),
                              forced_turnovers=1.0 + kept * (forced / weight - 1.0))
    return out


