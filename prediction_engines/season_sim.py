def spread_minutes(preferred, total=TEAM_MINUTES, cap=MINUTES_CAP):
    """Scale preferred minutes to the team's total without anyone passing the cap."""
    minutes = list(preferred)
    for _ in range(8):
        minutes = [min(cap, m) for m in minutes]
        short = total - sum(minutes)
        room = [i for i, m in enumerate(minutes) if m < cap - 1e-9]
        if abs(short) < 1e-6 or not room:
            break
        base = sum(minutes[i] for i in room)
        factor = (base + short) / base if base > 0 else 1.0
        for i in room:
            minutes[i] *= factor
    return minutes


def described_names(players):
    """How each player is named in an assist description.

    The bare surname, as the feed writes it - or, where dressed teammates
    share one, the surname with the shortest first-name prefix that tells
    them apart ("Jal. Williams", "Jay. Williams").
    """
    key = value_engine.name_key
    by_surname = defaultdict(list)
    for i, p in enumerate(players):
        by_surname[key(p.surname)].append(i)
    names = [p.surname for p in players]
    for indexes in by_surname.values():
        if len(indexes) < 2:
            continue
        firsts = {i: "".join(ch for ch in key(players[i].first) if ch.isalpha()) for i in indexes}
        for i in indexes:
            others = [firsts[j] for j in indexes if j != i]
            length = next((n for n in (1, 2, 3)
                           if not any(o[:n] == firsts[i][:n] for o in others)), 3)
            prefix = firsts[i][:length].capitalize()
            if prefix:
                names[i] = f"{prefix}. {players[i].surname}"
    return names


class TeamSheet:
    """One team's rotation for one game, with the tables the sampler draws from."""

    def __init__(self, prior, players, minutes):
        self.prior = prior
        self.tricode = prior.tricode
        self.team_id = prior.team_id
        self.players = players
        self.minutes = minutes
        self.described = described_names(players)
        self.initialled = [f"{p.first[:1]}. {p.surname}" for p in players]
        self.totals = {}
        self._cumulative = {}
        for kind in RATE_KINDS:
            weights = [m * p.rates[kind] for p, m in zip(players, minutes)]
            self.totals[kind] = sum(weights)
            self._cumulative[kind] = list(itertools.accumulate(weights))

    def pick(self, kind, rng, exclude=None):
        """A player drawn in proportion to minutes x his rate of `kind`."""
        cumulative = self._cumulative[kind]
        total = cumulative[-1]
        last = len(cumulative) - 1
        if total <= 0:
            return rng.randrange(last + 1)
        for _ in range(8):
            i = min(bisect.bisect_right(cumulative, rng.random() * total), last)
            if i != exclude:
                return i
        return next(i for i in range(last + 1) if i != exclude)


class Availability:
    """Who is out tonight: a two-state chain per player, so absences come in spells."""

    def __init__(self, rng):
        self._rng = rng
        self._out = {}

    def is_available(self, profile):
        p = profile.availability
        out = self._out.get(profile.person_id)
        if out is None:
            out = self._rng.random() > p
        elif out:
            out = self._rng.random() < ABSENCE_PERSISTENCE
        else:
            out = self._rng.random() < min(0.9, (1 - p) * (1 - ABSENCE_PERSISTENCE) / p)
        self._out[profile.person_id] = out
        return not out


def dressed_sheet(prior, roster, availability):
    """Tonight's rotation from a roster: the available, by how much they play."""
    status = [(p, availability.is_available(p)) for p in roster]
    available = [p for p, ok in status if ok]
    if len(available) < 8:                      # never fewer than eight in uniform
        missing = sorted((p for p, ok in status if not ok), key=lambda p: -p.minutes_per_game)
        available += missing[:8 - len(available)]
    rotation = sorted(available, key=lambda p: -p.minutes_per_game)[:ROTATION_SIZE]
    return TeamSheet(prior, rotation, spread_minutes([p.minutes_per_game for p in rotation]))


