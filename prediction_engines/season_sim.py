@dataclass
class SimulatedGame:
    game_id: str
    home: str
    away: str
    home_points: int
    away_points: int
    periods: int
    events: list               # tuples in PBP_COLUMNS order; empty in fast runs
    lines: list                # one dict per player who dressed

    def frame(self):
        return pd.DataFrame(self.events, columns=PBP_COLUMNS)


def clock_text(seconds):
    seconds = max(0.0, seconds)
    return f"PT{int(seconds // 60):02d}M{seconds % 60:05.2f}S"


def _draw(table, rng):
    u, running = rng.random(), 0.0
    for label, share in table:
        running += share
        if u < running:
            return label
    return table[-1][0]


def _clip(value, low, high):
    return max(low, min(high, value))


class GameSimulator:
    """Draws one game's possessions and writes them as play-by-play rows."""

    def __init__(self, league, rng, keep_events=True):
        self.league = league
        self.rng = rng
        self.keep_events = keep_events
        self._level = {k: TEAM_MINUTES * league.rates[k] for k in RATE_KINDS}

    def play(self, game_id, home, away):
        rng, level = self.rng, self._level
        sheets = (home, away)
        score = [0, 0]
        events = []
        lines = [[dict.fromkeys(LINE_STATS, 0) for _ in s.players] for s in sheets]
        team_fouls = [0, 0]
        team_turnovers = [0, 0]
        counter = [0]

        # Who is on offence is index t; d = 1 - t defends.
        shooting = [away.prior.defence * home.prior.form * (1 + HOME_EDGE),
                    home.prior.defence * away.prior.form * (1 - HOME_EDGE)]
        play_cut, p_oreb, p_oreb_ft, p_block, p_steal, p_assist, p_loose = [], [], [], [], [], [], []
        for t in (0, 1):
            off, de = sheets[t], sheets[1 - t]
            turnovers = off.totals["tov"] * de.prior.forced_turnovers / (1 - TEAM_TURNOVER_SHARE)
            # A defence that fouls a lot sends its opponents to the line more.
            trips = off.totals["trips"] * (de.totals["pf"] / level["pf"]) ** FOULING_EFFECT
            weights = [turnovers, off.totals["fga2"], off.totals["fga3"], trips]
            play_cut.append([w / sum(weights) for w in itertools.accumulate(weights)])
            boards = (off.totals["oreb"] / level["oreb"]) / max(1e-9, de.totals["dreb"] / level["dreb"])
            p_oreb.append(_clip(OREB_AFTER_SHOT * boards, 0.12, 0.45))
            p_oreb_ft.append(_clip(OREB_AFTER_FREE_THROW * boards, 0.04, 0.30))
            p_block.append(_clip(BLOCK_PER_MISSED_TWO * de.totals["blk"] / level["blk"], 0.03, 0.50))
            p_steal.append(_clip(STEAL_PER_TURNOVER * de.totals["stl"] / level["stl"], 0.20, 0.90))
            passing = off.totals["ast"] / level["ast"]
            p_assist.append({v: _clip(ASSISTED[v] * passing, 0.20, 0.97) for v in (2, 3)})
            p_loose.append(_clip(LOOSE_FOULS_PER_POSSESSION * de.totals["pf"] / level["pf"], 0.0, 0.25))

        def emit(period, clock, team, player, action, sub, text, value=0, result="", distance=0,
                 scored=False):
            counter[0] += 1
            if not self.keep_events:
                return
            n = counter[0]
            sheet = sheets[team] if team is not None else None
            p = sheet.players[player] if (sheet is not None and player is not None) else None
            events.append((
                game_id, n, clock_text(clock), period,
                sheet.team_id if sheet else 0, sheet.tricode if sheet else None,
                p.person_id if p else 0, p.surname if p else None,
                sheet.initialled[player] if p else None,
                0, 0, distance, result, 1 if value else 0,
                str(score[0]) if scored else None, str(score[1]) if scored else None,
                score[0] + score[1] if scored else 0,
                None if team is None else ("h" if team == 0 else "v"),
                text, action, sub, 0, value, n))

        def foul(period, clock, team, player, code, sub):
            line = lines[team][player]
            line["pf"] += 1
            team_fouls[team] += 1
            emit(period, clock, team, player, "Foul", sub,
                 f"{sheets[team].players[player].surname} {code} (P{line['pf']}.T{team_fouls[team]})")

        def rebound(period, clock, t, chance):
            """Who gets the miss; True when the offence keeps the ball."""
            offensive = rng.random() < chance
            side = t if offensive else 1 - t
            if rng.random() < TEAM_REBOUND_SHARE:
                emit(period, clock, side, None, "Rebound", "Unknown", f"{sheets[side].tricode} Rebound")
                return offensive
            who = sheets[side].pick("oreb" if offensive else "dreb", rng)
            line = lines[side][who]
            line["oreb" if offensive else "dreb"] += 1
            emit(period, clock, side, who, "Rebound", "Unknown",
                 f"{sheets[side].players[who].surname} REBOUND (Off:{line['oreb']} Def:{line['dreb']})")
            return offensive

        def free_throws(period, clock, t, shooter, shots):
            """Shoot `shots`; True when the last one missed and is live."""
            player = sheets[t].players[shooter]
            line = lines[t][shooter]
            missed_last = False
            for k in range(1, shots + 1):
                line["fta"] += 1
                if rng.random() < player.ft:
                    line["ftm"] += 1
                    line["pts"] += 1
                    score[t] += 1
                    emit(period, clock, t, shooter, "Free Throw", f"Free Throw {k} of {shots}",
                         f"{player.surname} Free Throw {k} of {shots} ({line['pts']} PTS)",
                         scored=True)
                    missed_last = False
                else:
                    emit(period, clock, t, shooter, "Free Throw", f"Free Throw {k} of {shots}",
                         f"MISS {player.surname} Free Throw {k} of {shots}")
                    missed_last = True
                    if k < shots:           # dead ball: the feed logs a team rebound
                        emit(period, clock, t, None, "Rebound", "Unknown",
                             f"{sheets[t].tricode} Rebound")
            return missed_last

        def turnover(period, clock, t):
            d = 1 - t
            team_turnovers[t] += 1
            if rng.random() < TEAM_TURNOVER_SHARE:
                emit(period, clock, t, None, "Turnover", "Shot Clock Turnover",
                     f"{sheets[t].tricode} Turnover: Shot Clock (T#{team_turnovers[t]})")
                return
            who = sheets[t].pick("tov", rng)
            line = lines[t][who]
            line["tov"] += 1
            surname = sheets[t].players[who].surname
            stolen = rng.random() < p_steal[t]
            kind = _draw(LIVE_TURNOVERS if stolen else DEAD_TURNOVERS, rng)
            if kind == "Offensive Foul Turnover":
                foul(period, clock, t, who, "OFF.FOUL", "Offensive")
            emit(period, clock, t, who, "Turnover", kind,
                 f"{surname} {kind} Turnover (P{line['tov']}.T{team_turnovers[t]})")
            if stolen:
                thief = sheets[d].pick("stl", rng)
                lines[d][thief]["stl"] += 1
                emit(period, clock, d, thief, "", "",
                     f"{sheets[d].players[thief].surname} STEAL ({lines[d][thief]['stl']} STL)")

        def shot(period, clock, t, value):
            """One field-goal attempt; True when the offence keeps the ball."""
            d = 1 - t
            shooter = sheets[t].pick("fga3" if value == 3 else "fga2", rng)
            player = sheets[t].players[shooter]
            line = lines[t][shooter]
            line["fga"] += 1
            if value == 3:
                line["fg3a"] += 1
                distance = rng.randint(23, 28)
                kind = "3PT Jump Shot"
            else:
                style = rng.random()
                distance = rng.randint(1, 3) if style < 0.55 else rng.randint(5, 20)
                kind = "Driving Layup" if style < 0.40 else ("Dunk" if style < 0.55 else "Jump Shot")
            # Score effects: a team ahead eases off and empties its bench, a team
            # behind presses. Without this the margins spread far wider than
            # real ones do - independent possessions give 19.9, the league 16.4.
            lead = _clip(score[t] - score[d], -SCORE_EFFECT_CAP, SCORE_EFFECT_CAP)
            skill = (player.fg3 if value == 3 else player.fg2) * shooting[t]
            chance = _clip(skill * (1.0 - SCORE_EFFECT * lead / 10.0), 0.05, 0.90)
            label = f"{player.surname} {distance}' {kind}"
            if rng.random() >= chance:
                emit(period, clock, t, shooter, "Missed Shot", kind, f"MISS {label}", value,
                     "Missed", distance)
                if value == 2 and rng.random() < p_block[t]:
                    blocker = sheets[d].pick("blk", rng)
                    lines[d][blocker]["blk"] += 1
                    emit(period, clock, d, blocker, "", "",
                         f"{sheets[d].players[blocker].surname} BLOCK ({lines[d][blocker]['blk']} BLK)")
                return rebound(period, clock, t, p_oreb[t])

            line["fgm"] += 1
            line["pts"] += value
            if value == 3:
                line["fg3m"] += 1
            score[t] += value
            text = f"{label} ({line['pts']} PTS)"
            if rng.random() < p_assist[t][value] and len(sheets[t].players) > 1:
                passer = sheets[t].pick("ast", rng, exclude=shooter)
                lines[t][passer]["ast"] += 1
                text += f" ({sheets[t].described[passer]} {lines[t][passer]['ast']} AST)"
            emit(period, clock, t, shooter, "Made Shot", kind, text, value, "Made", distance,
                 scored=True)
            if rng.random() < AND_ONE[value]:
                foul(period, clock, d, sheets[d].pick("pf", rng), "S.FOUL", "Shooting")
                if free_throws(period, clock, t, shooter, 1):
                    return rebound(period, clock, t, p_oreb_ft[t])
            return False

        def trip(period, clock, t):
            """A trip to the line; True when the offence keeps the ball."""
            d = 1 - t
            shooter = sheets[t].pick("trips", rng)
            shooting_foul = rng.random() >= BONUS_TRIPS
            foul(period, clock, d, sheets[d].pick("pf", rng),
                 "S.FOUL" if shooting_foul else "P.FOUL", "Shooting" if shooting_foul else "Personal")
            shots = 3 if (shooting_foul and rng.random() < THREE_SHOT_TRIPS) else 2
            if free_throws(period, clock, t, shooter, shots):
                return rebound(period, clock, t, p_oreb_ft[t])
            return False

        def possession(period, clock, t):
            """Play the possession out from `clock`; return the clock when it ended."""
            if rng.random() < p_loose[t]:
                foul(period, clock, 1 - t, sheets[1 - t].pick("pf", rng), "P.FOUL", "Personal")
            while True:
                u = rng.random()
                cut = play_cut[t]
                if u < cut[0]:
                    turnover(period, clock, t)
                    return clock
                keeps_ball = (shot(period, clock, t, 2) if u < cut[1] else
                              shot(period, clock, t, 3) if u < cut[2] else trip(period, clock, t))
                if not keeps_ball:
                    return clock
                clock -= rng.uniform(*SECONDS_AFTER_OREB)
                if clock <= 0:
                    return 0.0

        tempo = (home.prior.pace + away.prior.pace) / 2.0 * math.exp(rng.gauss(0, GAME_PACE_SD))
        mean_seconds = 1440.0 / tempo * PACE_TIME_FACTOR
        offence = rng.randrange(2)
        period = 0
        while True:
            period += 1
            remaining = 720.0 if period <= 4 else 300.0
            label = f"{ORDINALS[period]} Period" if period <= 4 else f"OT{period - 4}"
            emit(period, remaining, None, None, "period", "start", f"Start of {label}",
                 scored=(period == 1))
            while True:
                first_chance = rng.gammavariate(POSSESSION_SHAPE, mean_seconds / POSSESSION_SHAPE)
                if first_chance >= remaining:
                    break
                remaining = possession(period, remaining - first_chance, offence)
                offence = 1 - offence
                if remaining <= 0:
                    break
            emit(period, 0.0, None, None, "period", "end", f"End of {label}")
            if period >= 4 and score[0] != score[1]:
                break

        rows = []
        for t, sheet in enumerate(sheets):
            for i, player in enumerate(sheet.players):
                rows.append({"game_id": game_id, "team": sheet.tricode, "person_id": player.person_id,
                             "name": player.name, "minutes": sheet.minutes[i], **lines[t][i]})
        return SimulatedGame(game_id, home.tricode, away.tricode, score[0], score[1], period,
                             events, rows)


