def load_games():
    games = pd.read_pickle(GAMES_PATH).copy()
    games["game_id"] = games["game_id"].astype(str).str.zfill(10)
    games["game_date"] = pd.to_datetime(games["game_date"])
    return games


def load_box(games):
    """One row per player-game with minutes played, in plain column names."""
    box = pd.read_pickle(BOX_PLAYER_PATH)
    parts = box["min"].astype("string").str.extract(r"^(\d+)(?:\.\d+)?(?::(\d+))?")
    minutes = (pd.to_numeric(parts[0], errors="coerce").fillna(0)
               + pd.to_numeric(parts[1], errors="coerce").fillna(0) / 60.0)
    out = pd.DataFrame({
        "game_id": box["game_id"].astype(str).str.zfill(10),
        "team": box["team_abbreviation"].astype(str),
        "team_id": box["team_id"].astype("int64"),
        "person_id": box["player_id"].astype("int64"),
        "name": box["player_name"].astype(str),
        "minutes": minutes.astype(float),
    })
    renames = {"fgm": "fgm", "fga": "fga", "fg3_m": "fg3m", "fg3_a": "fg3a", "ftm": "ftm",
               "fta": "fta", "oreb": "oreb", "dreb": "dreb", "ast": "ast", "stl": "stl",
               "blk": "blk", "to": "tov", "pf": "pf", "pts": "pts"}
    for source, target in renames.items():
        out[target] = pd.to_numeric(box[source], errors="coerce").fillna(0.0).values
    out = out[out["minutes"] > 0]
    return out.merge(games[["game_id", "season", "game_date"]], on="game_id", how="inner")


