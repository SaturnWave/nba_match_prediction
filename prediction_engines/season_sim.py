def nba_season_label(season):
    """'2026_2027' -> '2026-27', the form the league's endpoints take."""
    start, end = season.split("_")
    return f"{start}-{end[2:]}"


def fetch_schedule(season, sandbox):
    """The published regular-season schedule, cached in the sandbox."""
    path = sandbox.path("schedule.csv")
    if os.path.exists(path):
        return pd.read_csv(path, dtype={"game_id": str})
    from nba_api.stats.endpoints import scheduleleaguev2
    raw = scheduleleaguev2.ScheduleLeagueV2(season=nba_season_label(season), league_id="00",
                                            timeout=60).get_data_frames()[0]
    regular = raw[raw["gameId"].astype(str).str.startswith("002")]
    fixed = regular[regular["homeTeam_teamTricode"].notna() & regular["awayTeam_teamTricode"].notna()]
    schedule = pd.DataFrame({
        "game_id": fixed["gameId"].astype(str).str.zfill(10),
        "game_date": fixed["gameDateEst"].astype(str).str[:10],
        "home": fixed["homeTeam_teamTricode"].astype(str),
        "away": fixed["awayTeam_teamTricode"].astype(str),
    }).sort_values(["game_date", "game_id"]).reset_index(drop=True)
    schedule.to_csv(path, index=False)
    print(f"  fikstur: {len(schedule)} mac (takimi belli olmayan {len(regular) - len(fixed)} mac haric)")
    return schedule


def fetch_rosters(season, team_ids, sandbox):
    """Current rosters from the league, cached in the sandbox."""
    path = sandbox.path("rosters.csv")
    if os.path.exists(path):
        return pd.read_csv(path)
    import requests
    from nba_api.stats.endpoints import commonteamroster
    frames = []
    for tricode, team_id in sorted(team_ids.items()):
        try:
            roster = commonteamroster.CommonTeamRoster(
                team_id=team_id, season=nba_season_label(season), timeout=60).get_data_frames()[0]
        except (requests.RequestException, ValueError, KeyError) as exc:
            raise RuntimeError(f"{tricode} kadrosu alinamadi ({type(exc).__name__}); "
                               f"tekrar calistirin - alinanlar saklanmadi") from exc
        frames.append(pd.DataFrame({"team": tricode, "person_id": roster["PLAYER_ID"].astype("int64"),
                                    "name": roster["PLAYER"].astype(str),
                                    "experience": roster["EXP"].astype(str)}))
        time.sleep(0.6)                     # the endpoint throttles bursts
    rosters = pd.concat(frames, ignore_index=True)
    rosters.to_csv(path, index=False)
    print(f"  kadrolar: {len(rosters)} oyuncu, {rosters['team'].nunique()} takim")
    return rosters


def opening_rosters(box, season):
    """Each player's team in his first game of the season - who started where."""
    first = (box[box["season"] == season].sort_values("game_date")
             .groupby("person_id").first().reset_index())
    return first[["team", "person_id", "name"]].assign(experience="")


def schedule_from_history(games, season):
    s = games[games["season"] == season].sort_values(["game_date", "game_id"])
    return pd.DataFrame({"game_id": s["game_id"], "game_date": s["game_date"].dt.strftime("%Y-%m-%d"),
                         "home": s["home_abbr"], "away": s["away_abbr"]}).reset_index(drop=True)


def previous_seasons(games, season, count):
    seasons = sorted(games["season"].unique())
    earlier = [s for s in seasons if s < season]
    return earlier[-count:]


